#!/usr/bin/env bash
#
# The contract: what a desktop that drives jayos-denoise may rely on.
#
#   tools/contract.sh            compare contract/ with what the code produces
#   tools/contract.sh --write    rewrite contract/ from the code
#
# Exit 0: contract/ is what the code produces (or was rewritten). 1: it is
# not, and the lines above say which file. 2: could not run (no jq), which is
# not the same answer as "current" and must not be read as one.
#
# Every file but README.md is made here, by RUNNING the engine and reading
# the library, never written by hand: a contract written by hand would be a
# second description of the code, and the two would drift. JayOS vendors a
# copy of this directory with each file's sha256 (its
# tools/fixtures/jayos-denoise-contract/PROVENANCE.md), and its suites hold
# its wrapper, its popup and its doctor to the copy.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENGINE="$ROOT/src/jayos-denoise"
LIB="$ROOT/src/easyeffects-lib.sh"
STEPS="$ROOT/packaging/steps.sh"
OUT="$ROOT/contract"

command -v jq >/dev/null 2>&1 || { echo "contract not exercised: jq is not installed" >&2; exit 2; }

WORK="$(mktemp -d "${TMPDIR:-/tmp}/denoise-contract.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

header() { # header <what> <made from>
    printf '# %s\n# Generated by tools/contract.sh from %s; do not edit.\n' "$1" "$2"
}

die() { echo "contract.sh: $*" >&2; exit 1; }

# This PATH with easyeffects subtracted: each directory that holds one is
# replaced by a directory of links to everything in it but that.
#
# NOT by dropping the directory. That was the first version, and on the
# machine this is for it is /usr/bin -- which also holds bash and jq, and
# /bin is the same directory -- so the PATH came out empty, `env` could not
# find the bash in the engine's #! line, and `status` failed: tools/check.sh
# reported the contract broken on every Arch machine with EasyEffects
# installed, and passed where it was not. RUN, by overlaying a fake
# easyeffects onto /usr/bin in a private mount namespace (exit 1, "env:
# 'bash': No such file or directory");
# tests/shell/test-contract.sh holds the case. Subtracting from the whole
# directory, rather than listing what the engine needs, is jayos's
# tools/lib/absent.sh technique and its reason: a list of tools to keep
# would be right until the engine called something new.
path_without_easyeffects() {
    local out="" d farm n=0
    local -a dirs
    IFS=: read -ra dirs <<<"$PATH"
    for d in "${dirs[@]}"; do
        [[ -n "$d" && -d "$d" ]] || continue
        if [[ -x "$d/easyeffects" ]]; then
            n=$((n + 1))
            farm="$WORK/path-without-easyeffects/$n"
            # One ln for the whole directory, which is not empty: it holds
            # easyeffects.
            mkdir -p "$farm" && ln -s "$d"/* "$farm/" && rm -f "$farm/easyeffects" || return 1
            d=$farm
        fi
        out+="${out:+:}$d"
    done
    printf '%s' "$out"
}

generate() { # generate <dir>
    local dir=$1 s names keys dirs noee

    # The schema of everything below. A reader refuses a newer one.
    printf '1\n' > "$dir/VERSION"

    # The verbs, as the engine's own usage says them.
    { header "The engine's command language, one form per line." "jayos-denoise's usage"
      "$ENGINE" --no-such-verb 2>&1 >/dev/null | sed -E 's/^(usage:|      ) //'
    } > "$dir/commands.txt"

    names=$("$ENGINE" strengths) || die "jayos-denoise strengths failed"
    { header "The strength names, in order. Any other name is refused for on." "jayos-denoise strengths"
      printf '%s\n' "$names"
    } > "$dir/strengths.txt"

    for s in $names; do
        # Byte for byte what `set` writes, not re-serialised: jq before 1.7
        # prints 24.0 as 24, so a contract passed through it would differ by
        # the jq that made it rather than by the code.
        "$ENGINE" preset "$s" > "$dir/preset.$s.json" || die "preset $s failed"
        "$ENGINE" preset "$s" off > "$dir/preset.$s.off.json" || die "preset $s off failed"
    done

    # The keys of `status`, in its order. Run with no EasyEffects on PATH,
    # where every key is still printed: a reader may rely on every key here,
    # and on no key that is not.
    noee=$(path_without_easyeffects) || die "could not make a PATH without easyeffects under $WORK"
    keys=$(env -i PATH="$noee" HOME="$WORK" "$ENGINE" status \
           | jq -r 'keys_unsorted[]') || die "jayos-denoise status failed"
    [[ -n "$keys" ]] || die "jayos-denoise status printed no keys"
    { header "The keys of jayos-denoise status, in its order." "jayos-denoise status"
      printf '%s\n' "$keys"
    } > "$dir/status-keys.txt"

    # The names a desktop writes into its own code: the preset's name, the
    # plugin's file and its key inside the preset, and where EasyEffects
    # looks for the file when LADSPA_PATH is unset.
    dirs=$(sed -n -E 's/.*\|\| dirs="([^"]*)".*/\1/p' "$LIB")
    [[ -n "$dirs" && "$dirs" != *$'\n'* ]] || die "could not read one default LADSPA list out of $LIB"
    { header "Names a desktop may write into its own code, one 'name value' per line." \
             "the engine, its library and its presets"
      printf 'preset-name %s\n' "$(sed -n -E 's/^PRESET_NAME="([^"]+)"$/\1/p' "$ENGINE")"
      printf 'plugin-file %s\n' "$(bash -c 'source "$1"; printf %s "$EE_PLUGIN_SO"' _ "$LIB")"
      printf 'plugin-key %s\n' "$(jq -r '.input.plugins_order[0]' "$dir/preset.balanced.json")"
      printf 'ladspa-dirs %s\n' "$dirs"
    } > "$dir/facts.txt"

    # The verbs of packaging/steps.sh, which JayOS's recipe calls: one per
    # arm of its dispatch, with as many arguments as the arm passes on --
    # "${2:-}" is the plugin tree, "${3:-}" the package directory.
    { header "The verbs of packaging/steps.sh, which JayOS's recipe calls, with their arguments." \
             "packaging/steps.sh's dispatch"
      sed -n '/^case "\${1:-}" in$/,/^esac$/p' "$STEPS" \
          | sed -n -E 's/^[[:space:]]+([a-z]+)\)[[:space:]]+(.*);;$/\1 \2/p' \
          | while read -r verb rest; do
                line=$verb
                [[ "$rest" == *'${2:-}'* ]] && line+=" <plugin-tree>"
                [[ "$rest" == *'${3:-}'* ]] && line+=" <pkgdir>"
                printf '%s\n' "$line"
            done
    } > "$dir/steps.txt"
    [[ $(grep -vc '^#' "$dir/steps.txt") -gt 0 ]] || die "read no verbs out of $STEPS"
}

GEN="$WORK/contract"
mkdir -p "$GEN"
generate "$GEN"

if [[ "${1:-}" == "--write" ]]; then
    mkdir -p "$OUT"
    # README.md is the one file written by hand; everything else is replaced,
    # and a file the code no longer produces is removed.
    find "$OUT" -maxdepth 1 -type f ! -name README.md -delete
    cp "$GEN"/* "$OUT/"
    echo "contract/ rewritten from the code"
    exit 0
fi

stale=0
for f in "$GEN"/*; do
    name=${f##*/}
    if [[ ! -f "$OUT/$name" ]]; then
        echo "  contract/$name is missing" ; stale=1
    elif ! cmp -s "$f" "$OUT/$name"; then
        echo "  contract/$name differs from what the code produces" ; stale=1
        diff "$OUT/$name" "$f" | sed 's/^/      /' | head -20
    fi
done
for f in "$OUT"/*; do
    name=${f##*/}
    [[ "$name" == README.md || -f "$GEN/$name" ]] || { echo "  contract/$name is produced by nothing"; stale=1; }
done
if (( stale )); then
    echo "contract/ is stale -- regenerate with tools/contract.sh --write, commit it, and re-vendor it into JayOS"
    exit 1
fi
echo "contract/ is current"
