#!/usr/bin/env bash
#
# The contract: what a desktop that drives jayos-denoise may rely on.
#
#   tools/contract.sh            compare contract/ with what the code produces
#   tools/contract.sh --write    rewrite contract/ from the code
#
# Exit 0: contract/ is what the code produces (or was rewritten). 1: it is
# not, and the lines above say which file. 2: could not run (no jq), which is
# not the same answer as "current" and must not be read as one.
#
# Every file but README.md is made here, by RUNNING the engine and reading
# the library, never written by hand: a contract written by hand would be a
# second description of the code, and the two would drift. JayOS vendors a
# copy of this directory with each file's sha256 (its
# tools/fixtures/jayos-denoise-contract/PROVENANCE.md), and its suites hold
# its wrapper, its popup and its doctor to the copy.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENGINE="$ROOT/src/jayos-audio"
SHIM="$ROOT/src/jayos-denoise"
LIB="$ROOT/src/easyeffects-lib.sh"
EE="$ROOT/src/easyeffects.sh"
STEPS="$ROOT/packaging/steps.sh"
OUT="$ROOT/contract"

command -v jq >/dev/null 2>&1 || { echo "contract not exercised: jq is not installed" >&2; exit 2; }

WORK="$(mktemp -d "${TMPDIR:-/tmp}/denoise-contract.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

header() { # header <what> <made from>
    printf '# %s\n# Generated by tools/contract.sh from %s; do not edit.\n' "$1" "$2"
}

die() { echo "contract.sh: $*" >&2; exit 1; }

# This PATH with easyeffects subtracted: each directory that holds one is
# replaced by a directory of links to everything in it but that.
#
# NOT by dropping the directory. That was the first version, and on the
# machine this is for it is /usr/bin -- which also holds bash and jq, and
# /bin is the same directory -- so the PATH came out empty, `env` could not
# find the bash in the engine's #! line, and `status` failed: tools/check.sh
# reported the contract broken on every Arch machine with EasyEffects
# installed, and passed where it was not. RUN, by overlaying a fake
# easyeffects onto /usr/bin in a private mount namespace (exit 1, "env:
# 'bash': No such file or directory");
# tests/shell/test-contract.sh holds the case. Subtracting from the whole
# directory, rather than listing what the engine needs, is jayos's
# tools/lib/absent.sh technique and its reason: a list of tools to keep
# would be right until the engine called something new.
path_without_easyeffects() {
    local out="" d farm n=0
    local -a dirs
    IFS=: read -ra dirs <<<"$PATH"
    for d in "${dirs[@]}"; do
        [[ -n "$d" && -d "$d" ]] || continue
        if [[ -x "$d/easyeffects" ]]; then
            n=$((n + 1))
            farm="$WORK/path-without-easyeffects/$n"
            # One ln for the whole directory, which is not empty: it holds
            # easyeffects.
            mkdir -p "$farm" && ln -s "$d"/* "$farm/" && rm -f "$farm/easyeffects" || return 1
            d=$farm
        fi
        out+="${out:+:}$d"
    done
    printf '%s' "$out"
}

generate() { # generate <dir>
    local dir=$1 s names keys dirs mark
    printf '2\n' > "$dir/VERSION"

    # The forms each command takes, from the usage block at the head of its
    # file: the first column of every `#   <command> ` line.
    forms() { # forms <file> <command>
        sed -n -E "s/^#   ($2 [^ ].*[^ ])  +.*$/\\1/p; s/^#   ($2 [^ ]+( [^ ]+)*)$/\\1/p" "$1" \
            | sed -E 's/[[:space:]]+$//' | awk '!seen[$0]++'
    }
    { header "jayos-denoise's forms, the 1.x verbs JayOS's denoise.sh hands on, one per line." "src/jayos-denoise's usage block"
      forms "$SHIM" jayos-denoise
    } > "$dir/commands.txt"
    { header "jayos-audio's forms, one per line." "src/jayos-audio's usage block"
      forms "$ENGINE" jayos-audio
    } > "$dir/engine-commands.txt"
    # The verbs `jayos-audio easyeffects` hands on, as the desktop may call
    # them: its hypr/easyeffects.sh passes every word it is given, so these
    # are what its popup, installer and doctor can rely on.
    { header "jayos-audio easyeffects's verbs, one per line." "src/easyeffects.sh's usage block"
      forms "$EE" easyeffects.sh | sed 's/^easyeffects\.sh /jayos-audio easyeffects /'
    } > "$dir/easyeffects-commands.txt"

    names=$("$ENGINE" denoise strengths) || die "jayos-audio denoise strengths failed"
    { header "The strength names, in order. Any other name is refused for on." "jayos-audio denoise strengths"
      printf '%s\n' "$names"
    } > "$dir/strengths.txt"

    # One host configuration per strength, with the plugin where the package
    # installs it and no microphone chosen: what a first start writes. A
    # plugin path that names no file makes the engine fall back to that path,
    # so the output is the same on every machine.
    for s in $names; do
        env -i PATH="$PATH" HOME="$WORK" XDG_STATE_HOME="$WORK/state" JAYOS_AUDIO_PLUGIN="$WORK/none" \
            "$ENGINE" denoise config "$s" > "$dir/config.$s.conf" || die "jayos-audio denoise config $s failed"
    done

    # With no session to ask: every key is printed whatever the answers are.
    keys=$(env -i PATH="$PATH" HOME="$WORK" XDG_STATE_HOME="$WORK/state" "$ENGINE" denoise status \
           | jq -r 'keys_unsorted[]') || die "jayos-audio denoise status failed"
    [[ -n "$keys" ]] || die "jayos-audio denoise status printed no keys"
    { header "The keys of jayos-audio denoise status, in its order." "jayos-audio denoise status"
      printf '%s\n' "$keys"
    } > "$dir/status-keys.txt"

    dirs=$(sed -n -E 's/^LADSPA_DIRS="([^"]*)"$/\1/p' "$ENGINE")
    [[ -n "$dirs" && "$dirs" != *$'\n'* ]] || die "could not read one LADSPA_DIRS out of $ENGINE"
    mark=$(cat "$ROOT"/packaging/patches/*.patch 2>/dev/null \
           | sed -n -E 's/^\+.*"DF \{\} \| Holding \{:\.1\}([^{"]+) \{\}.*$/\1/p')
    [[ -n "$mark" && "$mark" != *$'\n'* ]] \
        || die "could not read one headroom line out of packaging/patches/ (\"DF {} | Holding {:.1}ms for a quantum of {}\")"
    value() { # value <NAME> -- the literal NAME=... line of the engine
        local v
        v=$(sed -n -E "s/^$1=\"?([^\"]*)\"?$/\\1/p" "$ENGINE" | head -n 1)
        [[ -n "$v" ]] || die "could not read $1 out of $ENGINE"
        printf '%s' "$v"
    }
    { header "Names a desktop may write into its own code, one 'name value' per line." \
             "the engine and its patches"
      printf 'plugin-file %s\n' "$(value PLUGIN_SO)"
      printf 'ladspa-dirs %s\n' "$dirs"
      printf 'headroom-mark %s\n' "$mark"
      printf 'source-name %s\n' "$(value SOURCE)"
      printf 'capture-name %s\n' "$(value CAPTURE)"
      printf 'unit-name %s\n' "$(value UNIT)"
      printf 'floor-file %s\n' "$(sed -n -E 's/^DROPIN="\$\{JAYOS_AUDIO_FLOOR:-([^}]*)\}"$/\1/p' "$ENGINE")"
      printf 'retired-preset %s\n' denoise
    } > "$dir/facts.txt"
    grep -q '^floor-file /' "$dir/facts.txt" || die "could not read the floor's path out of $ENGINE"

    { header "The verbs of packaging/steps.sh, which JayOS's recipe calls, with their arguments." \
             "packaging/steps.sh's dispatch"
      sed -n '/^case "\${1:-}" in$/,/^esac$/p' "$STEPS" \
          | sed -n -E 's/^[[:space:]]+([a-z]+)\)[[:space:]]+(.*);;$/\1 \2/p' \
          | while read -r verb rest; do
                line=$verb
                [[ "$rest" == *'${2:-}'* ]] && line+=" <plugin-tree>"
                [[ "$rest" == *'${3:-}'* ]] && line+=" <pkgdir>"
                printf '%s\n' "$line"
            done
    } > "$dir/steps.txt"
    [[ $(grep -vc '^#' "$dir/steps.txt") -gt 0 ]] || die "read no verbs out of $STEPS"
}

GEN="$WORK/contract"
mkdir -p "$GEN"
generate "$GEN"

if [[ "${1:-}" == "--write" ]]; then
    mkdir -p "$OUT"
    # README.md is the one file written by hand; everything else is replaced,
    # and a file the code no longer produces is removed.
    find "$OUT" -maxdepth 1 -type f ! -name README.md -delete
    cp "$GEN"/* "$OUT/"
    echo "contract/ rewritten from the code"
    exit 0
fi

stale=0
for f in "$GEN"/*; do
    name=${f##*/}
    if [[ ! -f "$OUT/$name" ]]; then
        echo "  contract/$name is missing" ; stale=1
    elif ! cmp -s "$f" "$OUT/$name"; then
        echo "  contract/$name differs from what the code produces" ; stale=1
        diff "$OUT/$name" "$f" | sed 's/^/      /' | head -20
    fi
done
for f in "$OUT"/*; do
    name=${f##*/}
    [[ "$name" == README.md || -f "$GEN/$name" ]] || { echo "  contract/$name is produced by nothing"; stale=1; }
done
if (( stale )); then
    echo "contract/ is stale -- regenerate with tools/contract.sh --write, commit it, and re-vendor it into JayOS"
    exit 1
fi
echo "contract/ is current"
